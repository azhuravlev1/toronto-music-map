"""Merge research into data/events.js and archive past events.

    python3 tools/reload.py              # full reload from tools/research/*.json
    python3 tools/reload.py --prune-only # just archive + drop past events
"""
import argparse
import datetime as dt
import glob
import json
import os
import re
import sys
from zoneinfo import ZoneInfo

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
EVENTS_JS = os.path.join(ROOT, "data", "events.js")
VENUES_JS = os.path.join(ROOT, "data", "venues.js")
RESEARCH = os.path.join(ROOT, "tools", "research")
HISTORY = os.path.join(ROOT, "history", "past_events.txt")
WINDOW_DAYS = 21
TYPES = {"concert", "party", "comedy", "theatre", "dance", "sports", "film", "talk", "family", "festival", "other"}


def load_js(path, var):
    if not os.path.exists(path):
        return None
    src = open(path, encoding="utf-8").read()
    m = re.search(r"window\." + var + r"\s*=\s*(.*);\s*$", src, re.S)
    return json.loads(m.group(1))


def write_events(events, meta):
    events.sort(key=lambda e: (e["date"], e.get("time") or "99:99", e["venue"], e["title"].lower()))
    with open(EVENTS_JS, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/reload.py – do not hand-edit.\n")
        f.write("window.EVENTS = ")
        json.dump({"meta": meta, "events": events}, f, ensure_ascii=False, indent=1)
        f.write(";\n")


def archive(past, venue_names):
    if not past:
        return 0
    os.makedirs(os.path.dirname(HISTORY), exist_ok=True)
    existing = set(open(HISTORY, encoding="utf-8").read().splitlines()) if os.path.exists(HISTORY) else set()
    new = []
    for e in sorted(past, key=lambda e: (e["date"], e["venue"])):
        line = " | ".join([
            e["date"], e.get("time") or "--:--", venue_names.get(e["venue"], e["venue"]),
            e.get("type", "concert"), e["title"], e.get("url", ""),
        ])
        if line not in existing:
            new.append(line)
            existing.add(line)
    if new:
        header = not os.path.exists(HISTORY)
        with open(HISTORY, "a", encoding="utf-8") as f:
            if header:
                f.write("# date | time | venue | type | title | url\n")
            f.write("\n".join(new) + "\n")
    return len(new)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--prune-only", action="store_true")
    ap.add_argument("--today", help="override today (YYYY-MM-DD)")
    args = ap.parse_args()

    today = dt.date.fromisoformat(args.today) if args.today else dt.datetime.now(ZoneInfo("America/Toronto")).date()
    venues = {v["id"]: v["name"] for v in load_js(VENUES_JS, "VENUES")}
    current = load_js(EVENTS_JS, "EVENTS") or {"meta": {}, "events": []}

    past = [e for e in current["events"] if e["date"] < today.isoformat()]
    upcoming = [e for e in current["events"] if e["date"] >= today.isoformat()]
    archived = archive(past, venues)
    print(f"archived {archived} past events to {os.path.relpath(HISTORY, ROOT)}")

    if args.prune_only:
        meta = dict(current["meta"], prunedAt=today.isoformat())
        write_events(upcoming, meta)
        print(f"kept {len(upcoming)} upcoming events")
        return

    end = today + dt.timedelta(days=WINDOW_DAYS - 1)
    files = sorted(glob.glob(os.path.join(RESEARCH, "*.json")))
    if not files:
        sys.exit("no research files in tools/research/")

    merged, seen, problems = [], set(), []
    for path in files:
        for e in json.load(open(path, encoding="utf-8")):
            name = os.path.basename(path)
            if e.get("venue") not in venues:
                problems.append(f"{name}: unknown venue {e.get('venue')!r}")
                continue
            try:
                d = dt.date.fromisoformat(e["date"])
            except Exception:
                problems.append(f"{name}: bad date {e.get('date')!r}")
                continue
            if not (today <= d <= end):
                continue
            title = (e.get("title") or "").strip()
            if not title:
                problems.append(f"{name}: empty title on {e['date']}")
                continue
            typ = e.get("type", "concert")
            if typ not in TYPES:
                problems.append(f"{name}: unknown type {typ!r} -> other")
                typ = "other"
            key = (e["venue"], e["date"], title.lower())
            if key in seen:
                continue
            seen.add(key)
            ev = {"venue": e["venue"], "date": e["date"], "title": title, "url": e.get("url") or "", "type": typ}
            for opt in ("time", "emoji"):
                if e.get(opt):
                    ev[opt] = e[opt]
            merged.append(ev)

    meta = {"reloadedAt": today.isoformat(), "windowStart": today.isoformat(), "windowEnd": end.isoformat()}
    write_events(merged, meta)

    counts = {v: 0 for v in venues}
    for e in merged:
        counts[e["venue"]] += 1
    print(f"wrote {len(merged)} events for {today} .. {end} from {len(files)} research files")
    empty = [venues[v] for v, c in counts.items() if c == 0]
    if empty:
        print("venues with no events:", ", ".join(empty))
    for p in problems:
        print("warning:", p)


if __name__ == "__main__":
    main()
